"""### Part 5 - Average U.S. Daily Birth Data

You will now create a graph using average daily birth data in the U.S.

### Numpy Array Creation & Slicing

Slice the array to create the x and y-axis values. These will correspond to the following columns in the CSV linked on the HW instructions page:

*   x - Date
*   y_1 - Births
"""

data_births = np.genfromtxt('2012-US-Birth-Rates.csv', delimiter=',', dtype=str, skip_header=1)

x = data_births[:, 0]
y_1 = data_births[:, 1].astype(float)

"""### Graphing the Data

Plot x and y_1 with the elements shown in the instructions in the code block below.
"""

# Explanation for holiday drops: Sharp drops occur on major holidays (New Year's, July 4th, Labor Day, Thanksgiving, Christmas)
# because scheduled C-sections and induced labors are rarely booked on holidays and weekends.

plt.figure(figsize=(12, 4))
plt.plot(x, y_1, color='blue', linewidth=1)

# Curved annotations pointing to major holiday troughs
holidays = [
    ("New Year's Day", 0, -1500, .2),
    ("Independence Day", 185, -1800, -.2),
    ("Labor Day", 246, -1800, .2),
    ("Thanksgiving", 326, -1800, -.2),
    ("Christmas", 359, -1500, .2)
]

for label, idx, y_offset, curvature in holidays:
    plt.annotate(
        label,
        xy=(idx, y_1[idx]),
        xytext=(idx + 5, y_1[idx] + y_offset),
        arrowprops=dict(arrowstyle="->", connectionstyle=f"arc3,rad={curvature}", color='black')
    )

plt.title('U.S. Birth Rates (2012)')
plt.xlabel('Date')
plt.ylabel('Births')
plt.xticks(x[::30], rotation=45)
plt.grid(True)
plt.show()