import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

L = 6.0
R_A = 170.0
R_B = 410.0
P_1 = 100.0
q_1 = 120.0
q_2 = 120.0

x = np.linspace(0, L, 500)
V = np.zeros_like(x)

for i in range(len(x)):
    if x[i] < 2:
        V[i] = R_A - (q_1 * x[i])
    elif 2 <= x[i] <= 4:
        V[i] = R_A - (q_1 * 2) - P_1
    else:
        V[i] = R_A - (q_1 * 2) - P_1 + R_B - (q_2 * (x[i] - 4))

plt.plot(x, V, color='green')
plt.fill_between(x, V, color='lightgreen', alpha=0.5)
plt.axhline(0, color='black', linestyle='--')
plt.title('Shear Diagram')
plt.xlabel('Length (ft)')
plt.ylabel('Shear Force (lb)')
plt.grid(True)
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

L = 6.0
R_A = 170.0
R_B = 410.0
P_1 = 100.0
q_1 = 120.0
q_2 = 120.0

x = np.linspace(0, L, 500)
M = np.zeros_like(x)

for i in range(len(x)):
    if x[i] < 2:
        M[i] = (R_A * x[i]) - (q_1 * (x[i]**2) / 2)
    elif 2 <= x[i] <= 4:
        M[i] = (R_A * x[i]) - (q_1 * 2 * (x[i] - 1)) - (P_1 * (x[i] - 2))
    else:
        M[i] = (R_A * x[i]) - (q_1 * 2 * (x[i] - 1)) - (P_1 * (x[i] - 2)) + (R_B * (x[i] - 4)) - (q_2 * ((x[i] - 4)**2) / 2)

plt.plot(x, M, color='red')
plt.fill_between(x, M, color='lightcoral', alpha=0.5)
plt.axhline(0, color='black', linestyle='--')
plt.title('Moment Diagram')
plt.xlabel('Length (ft)')
plt.ylabel('Moment (lb-ft)')
plt.grid(True)
plt.show()

